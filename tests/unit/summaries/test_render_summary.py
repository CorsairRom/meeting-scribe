from returns.result import Failure, Success

from meeting_scribe.summaries.domain.errors import SummaryOutputInvalidError
from meeting_scribe.summaries.domain.headings import ENGLISH, EnglishHeadingCatalog
from meeting_scribe.summaries.domain.renderer import parse_body, render_summary
from tests.unit.summaries.factories import request
from tests.unit.summaries.fakes import LOCALIZED, LOCALIZED_OUTPUT

MODEL_OUTPUT = """# Weekly sync
## Topics
### 1. Planning
- point one
## Decisions
- ship on friday
## Action items
| Owner | Task |
|---|---|
| Person A | write it |
## Open questions
- who reviews?
"""


def test_header_is_computed_locally() -> None:
    req = request()
    body = parse_body(MODEL_OUTPUT, ENGLISH).unwrap()

    text = render_summary(req, body, ENGLISH)

    lines = text.markdown.splitlines()
    assert lines[0] == "# Weekly sync - 2031-03-04 (14:05, ~45 min)"
    assert lines[1] == "**Participants:** Person A, Person B"
    assert lines[2] == "**Generated by:** Fake provider / fake-model on 2031-03-05"
    assert lines[3].startswith("> Note: the transcript may contain recognition errors")
    assert text.title == "Weekly sync"


def test_sections_follow_the_reference_order() -> None:
    body = parse_body(MODEL_OUTPUT, ENGLISH).unwrap()

    markdown = render_summary(request(), body, ENGLISH).markdown

    positions = [
        markdown.index(heading)
        for heading in ("## Topics", "## Decisions", "## Action items", "## Open questions")
    ]
    assert positions == sorted(positions)
    assert "- ship on friday" in markdown
    assert "| Person A | write it |" in markdown


def test_empty_sections_say_none() -> None:
    output = "# T\n## Topics\n## Decisions\n- d\n## Action items\n## Open questions\n"

    markdown = render_summary(request(), parse_body(output, ENGLISH).unwrap(), ENGLISH).markdown

    assert markdown.count("None") == 3


def test_other_languages_fall_back_to_english_headings() -> None:
    catalog = EnglishHeadingCatalog()

    assert catalog.headings_for("xx") == ENGLISH
    assert catalog.headings_for("es") == ENGLISH


def test_localized_headings_are_parsed_and_rendered() -> None:
    body = parse_body(LOCALIZED_OUTPUT, LOCALIZED).unwrap()

    markdown = render_summary(request(language="zz"), body, LOCALIZED).markdown

    assert "## Alpha topics" in markdown
    assert "**Theta participants:** Person A, Person B" in markdown
    assert "> Kappa note" in markdown
    assert "## Topics" not in markdown


def test_english_headings_are_not_accepted_when_localized_ones_are_required() -> None:
    assert isinstance(parse_body(MODEL_OUTPUT, LOCALIZED), Failure)


def test_a_missing_section_is_invalid() -> None:
    result = parse_body("# T\n## Topics\n- a\n", ENGLISH)

    assert isinstance(result, Failure)
    assert isinstance(result.failure(), SummaryOutputInvalidError)


def test_a_missing_title_is_invalid() -> None:
    output = MODEL_OUTPUT.split("\n", 1)[1]

    assert isinstance(parse_body(output, ENGLISH), Failure)


def test_sections_out_of_order_are_invalid() -> None:
    output = "# T\n## Decisions\n- d\n## Topics\n- t\n## Action items\n## Open questions\n"

    assert isinstance(parse_body(output, ENGLISH), Failure)


def test_blank_output_is_invalid() -> None:
    assert isinstance(parse_body("  \n ", ENGLISH), Failure)


def test_parse_accepts_extra_blank_lines_and_heading_case() -> None:
    output = "\n# T\n\n## topics\n\n- a\n\n## DECISIONS\n- d\n## Action Items\n## open questions\n"

    assert isinstance(parse_body(output, ENGLISH), Success)
