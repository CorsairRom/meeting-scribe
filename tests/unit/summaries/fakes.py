class FakeHeadingCatalog:
    """Localized headings for the listed languages, English for the rest; records each ask."""

    def __init__(self, known: dict[str, Headings] | None = None) -> None:
        self.known = known if known is not None else {"zz": LOCALIZED}
        self.asked: list[str] = []

    def headings_for(self, language: str) -> Headings:
        self.asked.append(language)
        return self.known.get(language, ENGLISH)


Responder = Callable[[list[Message]], str | Completion | SummaryError]


def by_prompt_kind(
    notes: str = "- note", merged: str = "- merged", final: str = VALID_OUTPUT
) -> Responder:
    """Map notes, merged notes, and ``final`` for the final and repair requests."""

    def respond(messages: list[Message]) -> str:
        system = messages[0].content
        if system.startswith("You extract compact notes"):
            return notes
        if system.startswith("You merge partial"):
            return merged
        return final

    return respond


class FakeProvider:
    """Records every request; answers from ``responder`` (never raises)."""

    def __init__(self, responder: Responder | None = None) -> None:
        self.responder = responder or by_prompt_kind()
        self.requests: list[list[Message]] = []
        self.limits: list[CompletionLimits] = []
        self.on_call: Callable[[int], None] | None = None
        self.timeouts: list[float | None] = []
        self.block_until_cancelled = False
        self.sessions: list[str | None] = []

    def complete(
        self,
        messages: list[Message],
        limits: CompletionLimits,
        cancel: CancelSignal,
        timeout_seconds: float | None = None,
        session_id: str | None = None,
    ) -> Result[Completion, SummaryError]:
        self.requests.append(messages)
        self.sessions.append(session_id)
        self.timeouts.append(timeout_seconds)
        if self.block_until_cancelled:
            cancel.wait(5.0)
            return Failure(SummaryCancelledError("aborted"))
        self.limits.append(limits)
        if self.on_call is not None:
            self.on_call(len(self.requests))
        answer = self.responder(messages)
        if isinstance(answer, SummaryError):
            return Failure(answer)
        if isinstance(answer, str):
            return Success(Completion(text=answer, finish_reason="stop"))
        return Success(answer)


class FakeReleaser:
    def __init__(self) -> None:
        self.calls = 0

    def release(self) -> None:
        self.calls += 1


class FakeCancel:
    def __init__(self) -> None:
        self._set = False

    def set(self) -> None:
        self._set = True

    def is_set(self) -> bool:
        return self._set

    def wait(self, timeout: float | None = None) -> bool:  # noqa: ARG002
        return self._set


class FakeClock:
    def __init__(self) -> None:
        self.now = 0.0

    def __call__(self) -> float:
        return self.now


class FakeLocalModels:
    """A ``LocalModelSource`` answering a preset result (unavailable by default)."""

    def __init__(self, result: Result[list[ModelEntry], SummaryError] | None = None) -> None:
        self.result: Result[list[ModelEntry], SummaryError] = result or Failure(
            SummaryModelsUnavailableError("no list in this test")
        )
        self.asks = 0

    def list_models(self) -> Result[list[ModelEntry], SummaryError]:
        self.asks += 1
        return self.result


class FakeCloudModels:
    """A ``CloudModelSource`` answering a preset result; remembers that it got a key, not which."""

    def __init__(self, result: Result[list[ModelEntry], SummaryError] | None = None) -> None:
        self.result: Result[list[ModelEntry], SummaryError] = result or Failure(
            SummaryModelsUnavailableError("no list in this test")
        )
        self.asks = 0

    def list_models(self, key: SecretStr) -> Result[list[ModelEntry], SummaryError]:
        assert key.get_secret_value()
        self.asks += 1
        return self.result
