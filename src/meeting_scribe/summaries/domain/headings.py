"""Per-language section headings and fixed labels (spec 11).

Only English is shipped: every other language gets English headings with a body written in the
meeting language. A language is added by adding one entry to ``_TABLE``.
"""

from pydantic import BaseModel, ConfigDict


class Headings(BaseModel):
    model_config = ConfigDict(frozen=True)

    topics: str
    decisions: str
    action_items: str
    open_questions: str
    owner: str
    task: str
    none: str
    participants: str
    generated_by: str
    note: str

    @property
    def sections(self) -> tuple[str, str, str, str]:
        return (self.topics, self.decisions, self.action_items, self.open_questions)


ENGLISH = Headings(
    topics="Topics",
    decisions="Decisions",
    action_items="Action items",
    open_questions="Open questions",
    owner="Owner",
    task="Task",
    none="None",
    participants="Participants",
    generated_by="Generated by",
    note="Note: the transcript may contain recognition errors in names and technical terms.",
)

_TABLE = {"en": ENGLISH}

_LANGUAGE_NAMES = {
    "en": "English",
    "es": "Spanish",
    "fr": "French",
    "de": "German",
    "pt": "Portuguese",
    "it": "Italian",
}


def headings_for(language: str) -> Headings:
    return _TABLE.get(language, ENGLISH)


def language_name(language: str) -> str:
    """An English name for the prompt; an unknown code is used as given."""
    return _LANGUAGE_NAMES.get(language, language)
